<?php

require_once "config.php";

/*
|--------------------------------------------------------------------------
| Ambil Short Code
|--------------------------------------------------------------------------
*/

$code = $_GET["c"] ?? "";

if (empty($code)) {
    http_response_code(404);
    exit("404 - Short Link Tidak Ditemukan");
}

/*
|--------------------------------------------------------------------------
| Baca Database
|--------------------------------------------------------------------------
*/

$db = readDatabase();

/*
|--------------------------------------------------------------------------
| Cek Short Code
|--------------------------------------------------------------------------
*/

if (!isset($db[$code])) {
    http_response_code(404);
    exit("404 - Short Link Tidak Ditemukan");
}

/*
|--------------------------------------------------------------------------
| Tambah Jumlah Klik
|--------------------------------------------------------------------------
*/

$db[$code]["clicks"]++;

saveDatabase($db);

/*
|--------------------------------------------------------------------------
| Redirect
|--------------------------------------------------------------------------
*/

header("Location: " . $db[$code]["url"]);
exit;